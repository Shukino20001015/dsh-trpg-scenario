// Public character-state data is untrusted even when it comes from a model.
// This module validates structure and dialogue references, not their meaning
// or whether the text reveals a secret. Callers must enforce session scope.
import { resolveEvidenceQuotes } from './stage-graph.js'

const ID = /^[A-Za-z0-9_-]{1,48}$/
const exact = (value, keys) => value && typeof value === 'object' && !Array.isArray(value) && Object.keys(value).sort().join(',') === [...keys].sort().join(',')
const text = (value, max) => typeof value === 'string' && value === value.trim() && value.length > 0 && value.length <= max && !/[\u0000-\u001f\u007f]/.test(value)

// The public configuration is separate from private scenario notes; no field
// can be generated by copying or summarising the hidden setting implicitly.
export function parseCharacterConfig(source) {
  if (typeof source !== 'string' || Buffer.byteLength(source, 'utf8') > 16384) throw new Error('主角状态配置无效')
  let config
  try { config = JSON.parse(source) } catch { throw new Error('主角状态配置不是有效 JSON') }
  if (!exact(config, ['version', 'fields']) || config.version !== 1 || !Array.isArray(config.fields) || config.fields.length < 1 || config.fields.length > 12) throw new Error('主角状态配置无效')
  const seen = new Set()
  for (const field of config.fields) {
    if (!exact(field, ['id', 'label', 'initial']) || typeof field.id !== 'string' || !ID.test(field.id) || seen.has(field.id) || !text(field.label, 40) || !text(field.initial, 240)) throw new Error('主角状态字段无效')
    seen.add(field.id)
  }
  return config
}

export function initialCharacterState(config) {
  return { revision: 0, values: Object.fromEntries(config.fields.map(field => [field.id, field.initial])), history: [] }
}

export function restoreCharacterState(config, history) {
  if (!Array.isArray(history) || history.length > 10000) throw new Error('主角状态历史无效')
  const state = initialCharacterState(config)
  const ids = new Set(config.fields.map(field => field.id))
  for (const item of history) {
    if (!exact(item, ['revision', 'field', 'value', 'evidence']) || item.revision !== state.revision + 1 || !ids.has(item.field) || !text(item.value, 240) || item.value === state.values[item.field] || !Array.isArray(item.evidence) || item.evidence.length < 1 || item.evidence.length > 8 || new Set(item.evidence).size !== item.evidence.length || item.evidence.some(seq => !Number.isSafeInteger(seq) || seq < 0)) throw new Error('主角状态历史损坏')
    state.values[item.field] = item.value
    state.revision = item.revision
    state.history.push({ revision: item.revision, field: item.field, value: item.value, evidence: [...item.evidence] })
  }
  return state
}

export function advanceCharacterState(config, history, request, events) {
  const current = restoreCharacterState(config, history)
  if (current.history.length >= 10000) throw new Error('主角状态历史已达上限，无法继续更新')
  if (!exact(request, ['expectedRevision', 'field', 'value', 'quotes']) || !Number.isSafeInteger(request.expectedRevision) || request.expectedRevision !== current.revision) throw new Error('主角状态申请无效或版本已变化')
  if (!config.fields.some(field => field.id === request.field) || !text(request.value, 240) || request.value === current.values[request.field]) throw new Error('主角状态内容无效或没有变化')
  const evidence = resolveEvidenceQuotes(request.quotes, events)
  // An instruction such as “去睡觉” does not prove that the attempt completed.
  // Require at least one already-visible host statement as supporting evidence.
  // This structural check still cannot prove that the text supports the value.
  if (!evidence.some(seq => events.some(event => event.seq === seq && event.role === 'assistant'))) throw new Error('主角状态需要已显示的主持叙述作为依据')
  const entry = { revision: current.revision + 1, field: request.field, value: request.value, evidence }
  return restoreCharacterState(config, [...current.history, entry])
}

export function publicCharacterState(config, history) {
  const current = restoreCharacterState(config, history)
  return { revision: current.revision, fields: config.fields.map(field => ({ label: field.label, value: current.values[field.id] })) }
}
